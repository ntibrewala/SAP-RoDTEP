// Local JSON fallback store in case HANA_RO is used in dev environment without DDL/DML privileges
const CANDIDATE_STORE_PATHS = [
  "D:\\BHV\\rod\\rodtep_local_store.json",
  "D:\\BHV\\Config\\rodtep_local_store.json",
  "D:\\BHV\\rodtep\\rodtep_local_store.json",
  "N:\\SAP-RoDTEP\\SAP-RoDTEP\\rodtep_local_store.json",
  path.join(__dirname, "..", "rodtep_local_store.json")
];

function getPrimaryStorePath() {
  if (process.platform === "win32") {
    try {
      const dir = "D:\\BHV\\rod";
      if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
      return "D:\\BHV\\rod\\rodtep_local_store.json";
    } catch (_) {}
  }
  return path.join(__dirname, "..", "rodtep_local_store.json");
}

function readLocalStore() {
  const primary = getPrimaryStorePath();
  if (fs.existsSync(primary)) {
    try {
      const parsed = JSON.parse(fs.readFileSync(primary, "utf8"));
      if ((parsed.scrips && parsed.scrips.length > 0) || (parsed.utilizations && parsed.utilizations.length > 0)) {
        return {
          scrips: parsed.scrips || [],
          utilizations: parsed.utilizations || []
        };
      }
    } catch (_) {}
  }

  for (const p of CANDIDATE_STORE_PATHS) {
    try {
      if (fs.existsSync(p)) {
        const parsed = JSON.parse(fs.readFileSync(p, "utf8"));
        if ((parsed.scrips && parsed.scrips.length > 0) || (parsed.utilizations && parsed.utilizations.length > 0)) {
          return {
            scrips: parsed.scrips || [],
            utilizations: parsed.utilizations || []
          };
        }
      }
    } catch (_) {}
  }

  return { scrips: [], utilizations: [] };
}

function writeLocalStore(data) {
  const jsonStr = JSON.stringify(data, null, 2);
  const primary = getPrimaryStorePath();
  for (const t of CANDIDATE_STORE_PATHS) {
    try {
      if (t === primary || fs.existsSync(t)) {
        fs.writeFileSync(t, jsonStr, "utf8");
      }
    } catch (_) {}
  }
}

let hanaTablesReady = false;

async function ensureHanaTables() {
  if (hanaTablesReady) return true;
  try {
    const [existing] = await db.query(`
      SELECT "TABLE_NAME"
      FROM "SYS"."TABLES"
      WHERE "SCHEMA_NAME" = CURRENT_SCHEMA
        AND "TABLE_NAME" IN ('BHV_RODTEP_SCRIP', 'BHV_RODTEP_BL')
    `);
    const names = new Set((existing || []).map((r) => r.TABLE_NAME));

    if (!names.has("BHV_RODTEP_SCRIP")) {
      await db.execute(`
        CREATE COLUMN TABLE "BHV_RODTEP_SCRIP" (
          "LicNo"         NVARCHAR(50)   NOT NULL PRIMARY KEY,
          "LicDate"       DATE,
          "ExporterName"  NVARCHAR(200),
          "Scheme"        NVARCHAR(30),
          "PortCode"      NVARCHAR(30),
          "PortLocation"  NVARCHAR(50)   DEFAULT '',
          "ScripAmount"   DECIMAL(18, 2) NOT NULL,
          "APDocEntry"    INTEGER,
          "APDocNum"      INTEGER,
          "CardCode"      NVARCHAR(30),
          "CardName"      NVARCHAR(200),
          "NumAtCard"     NVARCHAR(100),
          "APDocDate"     DATE,
          "CreatedAt"     TIMESTAMP      DEFAULT CURRENT_TIMESTAMP
        )
      `);
    }

    if (!names.has("BHV_RODTEP_BL")) {
      await db.execute(`
        CREATE COLUMN TABLE "BHV_RODTEP_BL" (
          "Id"             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          "BLNo"           NVARCHAR(100)  NOT NULL,
          "PortLocation"   NVARCHAR(50)   DEFAULT '',
          "GRPODocEntry"   INTEGER,
          "GRPODocNum"     INTEGER,
          "DraftBOEAmount" DECIMAL(18, 2),
          "BOENo"          NVARCHAR(50),
          "LicNo"          NVARCHAR(50)   NOT NULL,
          "AmountUsed"     DECIMAL(18, 2) NOT NULL,
          "Remarks"        NVARCHAR(254),
          "CreatedAt"      TIMESTAMP      DEFAULT CURRENT_TIMESTAMP
        )
      `);
    }

    hanaTablesReady = true;
    return true;
  } catch (err) {
    console.warn("[RoDTEP] HANA DDL check/create note (using hybrid mode if RO user):", err.message);
    return false;
  }
}

function normalizePort(rawPort, whsName = "", portCode = "") {
  const s = `${rawPort || ""} ${whsName || ""} ${portCode || ""}`.toUpperCase();
  if (s.includes("CHENNAI") || s.includes("INMAA") || s.includes("INTUT") || s.includes("INBLR")) {
    return "Chennai";
  }
  if (s.includes("MUNDRA") || s.includes("INMUN") || s.includes("INNSA") || s.includes("INHZA") || s.includes("INDEL") || s.includes("INCOK")) {
    return "Mundra";
  }
  return rawPort ? String(rawPort).trim() : "";
}

function parseExcelDateToIso(val) {
  if (!val) return null;
  const s = String(val).trim();
  if (!s) return null;

  // YYYY-MM-DD
  let m = s.match(/^(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})/);
  if (m) {
    return `${m[1]}-${String(m[2]).padStart(2, "0")}-${String(m[3]).padStart(2, "0")}`;
  }

  // DD.MM.YYYY or DD/MM/YYYY or DD-MM-YYYY
  m = s.match(/^(\d{1,2})[-/.](\d{1,2})[-/.](\d{2,4})$/);
  if (m) {
    let d = Number(m[1]);
    let mo = Number(m[2]);
    let y = Number(m[3]);
    if (y < 100) y += 2000;
    return `${y}-${String(mo).padStart(2, "0")}-${String(d).padStart(2, "0")}`;
  }

  return null;
}

