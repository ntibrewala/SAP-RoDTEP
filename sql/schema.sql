-- =============================================================================
-- SAP HANA Schema Setup for RoDTEP / RoSCTL Scrip Management
-- Schema: BHAVYA_POLYFILMS_01
-- Design: Normalized 2-Table Structure (Utilized & Balance computed on-the-fly)
-- =============================================================================

SET SCHEMA "BHAVYA_POLYFILMS_01";

-- -----------------------------------------------------------------------------
-- TABLE 1: BHV_RODTEP_SCRIP (Scrip Purchase Master & SAP A/P Invoice Link)
-- Note: Does NOT store UtilizedAmount or BalanceAmount. Those are calculated
-- dynamically on the fly by summing BHV_RODTEP_BL.AmountUsed!
-- -----------------------------------------------------------------------------
CREATE COLUMN TABLE "BHAVYA_POLYFILMS_01"."BHV_RODTEP_SCRIP" (
    "LicNo"         NVARCHAR(50)   NOT NULL PRIMARY KEY,
    "LicDate"       DATE,
    "ExporterName"  NVARCHAR(200),
    "Scheme"        NVARCHAR(30),
    "PortCode"      NVARCHAR(30),
    "PortLocation"  NVARCHAR(50)   NOT NULL,
    "ScripAmount"   DECIMAL(18, 2) NOT NULL,
    "APDocEntry"    INTEGER,
    "APDocNum"      INTEGER,
    "CardCode"      NVARCHAR(30),
    "CardName"      NVARCHAR(200),
    "NumAtCard"     NVARCHAR(100),
    "APDocDate"     DATE,
    "CreatedAt"     TIMESTAMP      DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- TABLE 2: BHV_RODTEP_BL (BL / GRPO / Draft BOE Scrip Utilization Table)
-- Stores each attachment of a RoDTEP Scrip against a BL & GRPO, along with the
-- Draft BOE Amount so that SUM(AmountUsed) for a BL/GRPO is validated against DraftBOEAmount.
-- -----------------------------------------------------------------------------
CREATE COLUMN TABLE "BHAVYA_POLYFILMS_01"."BHV_RODTEP_BL" (
    "Id"             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BLNo"           NVARCHAR(100)  NOT NULL,
    "PortLocation"   NVARCHAR(50)   NOT NULL,
    "GRPODocEntry"   INTEGER,
    "GRPODocNum"     INTEGER,
    "DraftBOEAmount" DECIMAL(18, 2),
    "BOENo"          NVARCHAR(50),
    "LicNo"          NVARCHAR(50)   NOT NULL,
    "AmountUsed"     DECIMAL(18, 2) NOT NULL,
    "Remarks"        NVARCHAR(254),
    "CreatedAt"      TIMESTAMP      DEFAULT CURRENT_TIMESTAMP
);
